import type { AnalysisResult, ReleaseInfo } from "../types/analysis";

export function generateReleaseNotes(
  release: ReleaseInfo,
  repoName: string
): string {
  const lines: string[] = [
    `# ${repoName} ${release.tag}`,
    "",
    `**Date:** ${release.date.slice(0, 10)}  `,
    `**Commits:** ${release.commits}  `,
    `**Contributors:** ${release.contributors.length}`,
    "",
  ];
  if (release.previousTag) {
    lines.push(`Changes since \`${release.previousTag}\`.`, "");
  }

  const byCat = new Map(release.categories.map((c) => [c.category, c.count]));
  lines.push("## Summary", "");
  for (const [cat, count] of byCat) {
    lines.push(`- **${cat}:** ${count}`);
  }
  lines.push("");

  if (release.highlights.length) {
    lines.push("## Highlights", "");
    for (const h of release.highlights) {
      lines.push(`- ${h}`);
    }
    lines.push("");
  }

  lines.push("---", "", `*Generated by GitChronicle*`, "");
  return lines.join("\n");
}

export function generateRepositoryReport(result: AnalysisResult): string {
  const o = result.overview;
  const lines: string[] = [
    `# ${result.repository.name} — Repository Report`,
    "",
    `Generated ${result.generatedAt.slice(0, 10)} by GitChronicle.`,
    "",
    "## Overview",
    "",
    o.narrative,
    "",
    `| Metric | Value |`,
    `| --- | --- |`,
    `| Commits | ${o.commitCount} |`,
    `| Contributors | ${o.contributorCount} |`,
    `| Files | ${o.fileCount} |`,
    `| Age (days) | ${o.ageDays} |`,
    `| Active days | ${o.activeDays} |`,
    `| Tags | ${o.tagCount} |`,
    `| Lines added | ${o.totalAdditions} |`,
    `| Lines removed | ${o.totalDeletions} |`,
    "",
    "## Languages",
    "",
  ];

  for (const lang of result.languages.slice(0, 12)) {
    lines.push(
      `- **${lang.language}:** ${lang.count} files (${(lang.percent * 100).toFixed(1)}%)`
    );
  }

  lines.push("", "## Top contributors", "");
  for (const c of result.contributors.slice(0, 10)) {
    lines.push(
      `- **${c.name}** — ${c.commits} commits, ${c.activeDays} active days`
    );
  }

  lines.push("", "## Development eras", "");
  for (const era of result.eras) {
    lines.push(
      `### ${era.name} (${era.start} → ${era.end})`,
      "",
      era.summary,
      ""
    );
  }

  lines.push("## Hotspots", "");
  for (const h of result.hotspots.slice(0, 15)) {
    lines.push(
      `- \`${h.path}\` — risk ${h.riskScore}, churn ${h.churn}, ${h.commits} commits — ${h.riskReasons.join("; ")}`
    );
  }

  lines.push("", "## Releases", "");
  for (const r of result.releases.slice(0, 15)) {
    lines.push(
      `- **${r.tag}** (${r.date.slice(0, 10)}) — ${r.commits} commits`
    );
  }

  lines.push("", "## Milestones", "");
  for (const m of result.milestones.slice(0, 20)) {
    lines.push(
      `- **${m.date.slice(0, 10)}** [${m.kind}] ${m.title}: ${m.description}`
    );
  }

  lines.push("", "---", "", "*Generated by GitChronicle*", "");
  return lines.join("\n");
}
